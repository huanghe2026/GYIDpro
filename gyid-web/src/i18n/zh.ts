// as const 会让所有字段变成 readonly 字面量类型；这里递归宽化为普通 string 结构，
// 这样英文词典只需保持相同形状，无需逐字等于中文。
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly Widen<U>[]
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T;

export type Dict = Widen<typeof zh>;
